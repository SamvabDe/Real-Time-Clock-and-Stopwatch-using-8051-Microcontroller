ORG 8100H

MOV A ,#80H
MOV DPTR, #0E803H
MOVX @DPTR, A
MOV DPTR, #0E800H

LOOP:
MOV A, #00111111B ; 0
MOVX @DPTR, A
ACALL DELAY

MOV A, #00000110B ; 1
MOVX @DPTR, A
ACALL DELAY

MOV A, #01011011B ; 2
MOVX @DPTR, A
ACALL DELAY

MOV A, #01001111B ; 3
MOVX @DPTR, A
ACALL DELAY

MOV A, #01100110B ; 4
MOVX @DPTR, A
ACALL DELAY

MOV A, #01101101B ; 5
MOVX @DPTR, A
ACALL DELAY

MOV A, #01111101B ; 6
MOVX @DPTR, A
ACALL DELAY

MOV A, #00000111B ; 7
MOVX @DPTR, A
ACALL DELAY

MOV A, #01111111B ; 8
MOVX @DPTR, A
ACALL DELAY

MOV A, #01101111B ; 9
MOVX @DPTR, A
ACALL DELAY

SJMP LOOP

DELAY:
MOV R5,#8
L3:
MOV R4,#250
L2:
MOV R3,#250
L1:        ; delay=1000us=1s
DJNZ R3,L1
DJNZ R4,L2
DJNZ R5,L3
RET
END
