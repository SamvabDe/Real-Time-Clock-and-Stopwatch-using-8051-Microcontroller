START:
MOV A, #10000000B
MOV DPTR, #0E803H
MOVX @DPTR, A

MOV DPTR, #9500H
MOV R1, DPL
MOV R0, #25 ; total 25 numbers are there in the array

OUTER_LOOP:
MOV DPTR, #9500H ; STORED VALUES IN MEMORY LOCATION
MOV DPL, R1

MOVX A, @DPTR
MOV B, #10
DIV AB

MOV R4, A ; R4 <- QUOTIENT/TENS
MOV R5, B ; R5 <- REMAINDER/ONES

MOV DPTR, #9200H
MOV A, DPL
ADD A, R4
MOV DPL, A
MOVX A, @DPTR
MOV R6, A ; R6 <- LED CONFIG CORRESPONDING TO TENS

MOV DPTR, #9200H
MOV A, DPL
ADD A, R5
MOV DPL, A
MOVX A, @DPTR
MOV R7, A ; R7 <- LED CONFIG CORRESPONDING TO ONES

MOV TMOD, #01H
MOV R2, #50 ; R2 AND R3 CONTROLS # OF ITERATIONS OF TIMER OVERFLOW

TENS_DISP:
MOV TL0, #00H
MOV TH0, #0EEH
SETB TR0

MOV DPTR, #0E801H ; activating PORT B -> Common Cathode Pin
MOV A, #11111101B ; 2nd bit turns low as display is Active LOW
MOVX @DPTR, A

INNER_LOOP1:
MOV DPTR, #0E800H ; activating PORT A -> Segment Pin
MOV A, R6          
MOVX @DPTR, A
JNB TF0, INNER_LOOP1

CLR TR0
CLR TF0

ONES_DISP:
MOV TL0, #00H
MOV TH0, #0EEH
SETB TR0

MOV DPTR, #0E801H ; activating PORT B -> Common Cathode Pin
MOV A, #11111110B ; 1st bit turns low as display is Active LOW
MOVX @DPTR, A    

INNER_LOOP2:
MOV DPTR, #0E800H ; activating PORT A -> Segment Pin
MOV A, R7
MOVX @DPTR, A
JNB TF0, INNER_LOOP2

CLR TR0
CLR TF0

DJNZ R2, TENS_DISP

INC R1
DJNZ R0, OUTER_LOOP

SJMP START ;

END
